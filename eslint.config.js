import tsParser from '@typescript-eslint/parser'
import solid from 'eslint-plugin-solid'

/**
 * Solid-specific lint rules, deliberately narrow.
 *
 * Biome owns formatting, general correctness and the `solid` domain it ships.
 * This runs **only** `eslint-plugin-solid`, which knows Solid's reactivity model
 * and JSX idioms that Biome does not cover: destructuring props (which kills
 * reactivity), `.map()` where `<For>` belongs, `innerHTML`, the `style` prop.
 * Two linters is a cost; the alternative is not checking these at all.
 */
export default [
  {
    ignores: [
      '**/dist/**',
      '**/coverage/**',
      '**/node_modules/**',
      '**/test-results/**',
      '**/playwright-report/**',
      // Storybook's static build: generated output, gitignored, and not ours
      // to lint (it carries its own eslint-disable comments for plugins this
      // repo does not install).
      '**/storybook-static/**',
      'packages/tailwind/src/generated/**',
      // Generated by `pnpm site`: the registry and the per-component prop
      // tables. `site:check` gates their content; formatting them is noise.
      'apps/playground/src/generated/**',
      'e2e/**',
      // The reference checkouts (frappe-ui, solid-ui, zag). They carry their own
      // eslint configs, which resolve packages this repo does not install — so
      // scanning them is not merely slow, it crashes the linter.
      'references/**',
    ],
  },
  {
    files: ['**/*.{ts,tsx}'],
    languageOptions: {
      parser: tsParser,
      parserOptions: {
        ecmaFeatures: { jsx: true },
        sourceType: 'module',
      },
    },
    plugins: { solid },
    rules: {
      'solid/components-return-once': 'error',
      'solid/imports': 'error',
      'solid/jsx-no-duplicate-props': 'error',
      'solid/jsx-no-script-url': 'error',
      'solid/no-destructure': 'error',
      'solid/no-innerhtml': 'error',
      'solid/no-unknown-namespaces': 'error',
      'solid/prefer-for': 'error',
      'solid/prefer-show': 'error',
      'solid/reactivity': 'error',
      'solid/style-prop': 'error',
    },
  },
]
