/**
 * Runtime CSS custom properties, generated from the token data.
 *
 * `light` goes on `:root`, `dark` on `[data-theme="dark"]`. This is how the
 * theme flips without a single `dark:` variant: utilities resolve
 * `var(--surface-*)` / `var(--ink-*)` / `var(--outline-*)`, and this file is
 * what re-values those under the dark selector.
 *
 * Radius, typography, spacing and shadow are intentionally NOT emitted here:
 * those are static and owned by Tailwind's `@theme` block. Emitting them twice
 * would only create duplicate declarations.
 */
import { cssVariables } from './index.js'

/** Categorical series colours for charts, light and dark. */
const CHART_SERIES = [
  'blue',
  'green',
  'amber',
  'red',
  'violet',
  'cyan',
  'teal',
  'pink',
]

// The ramps are keyed by Tailwind's `50…950` scale, so a series pointer must
// name the three-digit step (`--blue-600`). A one-digit suffix (`--blue-6`)
// matches nothing: the custom property is guaranteed-invalid, every
// `var(--chart-*)` consumer falls back to `transparent`, and charts render
// invisible without any error.
function chartVariables(mode) {
  const out = {}
  CHART_SERIES.forEach((family, index) => {
    const ramp = mode === 'dark' ? '--dark-' : '--'
    out[`--chart-${index + 1}`] = `var(${ramp}${family}-600)`
  })
  return out
}

function block(selector, vars) {
  const body = Object.entries(vars)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join('\n')
  return `${selector} {\n${body}\n}`
}

export function tokensCss() {
  const light = Object.fromEntries(
    Object.entries(cssVariables.light).filter(
      ([name]) => !name.startsWith('--radius-'),
    ),
  )
  return [
    '/* Generated by @newui/tailwind `build:css`. Do not edit. */',
    block(':root', { ...light, ...chartVariables('light') }),
    block('[data-theme="dark"]', {
      ...cssVariables.dark,
      ...chartVariables('dark'),
    }),
    '',
  ].join('\n')
}
