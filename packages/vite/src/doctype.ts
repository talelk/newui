/**
 * DocType → TypeScript. Fetches DocType metadata from a Frappe backend and
 * emits interfaces a consumer passes to `useDoc`/`useDoctype`:
 *
 *   const task = useDoc<Task>({ doctype: 'Task', name: 'T-1' })
 *
 * The metadata → source mapping is pure and unit-tested; only
 * `generateDocTypes` performs I/O.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import type { Plugin } from 'vite'

/** A single DocType field, as it arrives from `frappe.client.get_meta`. */
export interface DocTypeField {
  fieldname: string
  fieldtype: string
  label?: string
  options?: string
  reqd?: boolean
}

/** The DocType metadata this package needs to emit an interface. */
export interface DocTypeMeta {
  name: string
  istable?: boolean
  fields: DocTypeField[]
}

/** Options for {@link generateDocTypes}. */
export interface GenerateDocTypesOptions {
  /**
   * Backend base URL, e.g. `http://127.0.0.1:8000`. Empty means same origin,
   * which is what the dev proxy gives you.
   * @default ''
   */
  url?: string
  /** DocType names to fetch and emit. */
  doctypes: string[]
  /**
   * Output file. Relative paths resolve against `process.cwd()`.
   * @default 'src/types/doctypes.ts'
   */
  output?: string
  /** Extra request headers, e.g. `Authorization` or `Cookie`. */
  headers?: Record<string, string>
  /**
   * `fetch` implementation. Defaults to the global; inject one to stub the
   * network in tests or to add a retry policy.
   */
  fetch?: typeof globalThis.fetch
}

/** What {@link generateDocTypes} reports back. */
export interface GenerateDocTypesResult {
  /** Absolute path that was (or would have been) written. */
  output: string
  /** `false` when the file was already up to date. */
  written: boolean
  /** The DocType names emitted, in input order. */
  doctypes: string[]
}

const FIELD_TYPE_MAP: Record<string, string> = {
  Data: 'string',
  'Text Editor': 'string',
  'Small Text': 'string',
  Text: 'string',
  'Long Text': 'string',
  Code: 'string',
  'Read Only': 'string',
  Password: 'string',
  Color: 'string',
  Autocomplete: 'string',
  Barcode: 'string',
  Link: 'string',
  'Dynamic Link': 'string',
  Date: 'string',
  Datetime: 'string',
  Time: 'string',
  Duration: 'string',
  Geolocation: 'string',
  Attach: 'string',
  'Attach Image': 'string',
  Int: 'number',
  Float: 'number',
  Percent: 'number',
  Currency: 'number',
  Check: '0 | 1',
}

const LAYOUT_FIELDTYPES = new Set([
  'Section Break',
  'Column Break',
  'Tab Break',
  'HTML',
  'Button',
])

const TABLE_FIELDTYPES = new Set(['Table', 'Table MultiSelect'])

// Required unless the schema says otherwise; these are always present.
const ALWAYS_PRESENT_FIELDTYPES = new Set([
  'Check',
  'Table',
  'Table MultiSelect',
])

/** The TS interface name for a DocType name: `"Sales Order"` → `SalesOrder`. */
export function toTypeName(name: string): string {
  return name.replace(/\s+/g, '')
}

/** The TypeScript type for one field. */
export function mapFieldType(field: DocTypeField): string {
  const { fieldtype, options } = field

  if (fieldtype === 'Select' && options) {
    const union = options
      .split('\n')
      .map((option) => option.trim())
      .filter(Boolean)
      .map((option) => `'${option.replace(/'/g, "\\'")}'`)
      .join(' | ')
    if (union) return union
  }

  if (TABLE_FIELDTYPES.has(fieldtype) && options) {
    return `${toTypeName(options)}[]`
  }

  return FIELD_TYPE_MAP[fieldtype] ?? 'any'
}

/** One interface property, or `null` for a layout-only field. */
export function fieldToProperty(field: DocTypeField): string | null {
  if (LAYOUT_FIELDTYPES.has(field.fieldtype)) return null

  let description = `/** ${field.label ?? field.fieldname}: ${field.fieldtype}`
  if (
    field.options &&
    (TABLE_FIELDTYPES.has(field.fieldtype) ||
      field.fieldtype === 'Link' ||
      field.fieldtype === 'Dynamic Link')
  ) {
    description += ` (${field.options})`
  }
  description += ' */'

  const optional =
    field.reqd || ALWAYS_PRESENT_FIELDTYPES.has(field.fieldtype) ? '' : '?'

  return `  ${description}\n  ${field.fieldname}${optional}: ${mapFieldType(field)};`
}

/** The complete generated file for a set of DocType metadata. */
export function generateDocTypeSource(metas: DocTypeMeta[]): string {
  const header = [
    '// Generated by @talelk/newui-vite. Do not edit by hand.',
    '// Refresh with `generateDocTypes()` from a script or the dev plugin.',
    '',
    '',
  ].join('\n')

  const base = [
    'export interface DocType {',
    '  name: string',
    '  creation: string',
    '  modified: string',
    '  owner: string',
    '  modified_by: string',
    '}',
    '',
    'export interface ChildDocType extends DocType {',
    '  parent?: string',
    '  parentfield?: string',
    '  parenttype?: string',
    '  idx?: number',
    '}',
    '',
  ].join('\n')

  const interfaces = metas.map((meta) => {
    const parent = meta.istable ? 'ChildDocType' : 'DocType'
    const properties = meta.fields
      .map(fieldToProperty)
      .filter((property): property is string => property !== null)
    const body = properties.length ? `${properties.join('\n')}\n` : ''
    return `export interface ${toTypeName(meta.name)} extends ${parent} {\n${body}}\n`
  })

  return `${header}${base}\n${interfaces.join('\n')}`
}

/**
 * Pull a {@link DocTypeMeta} out of a `frappe.client.get_meta` response,
 * tolerating both the `{ message: { docs: [meta] } }` and `{ message: meta }`
 * shapes. Exported for tests; not part of the documented surface.
 */
export function extractDocTypeMeta(
  payload: unknown,
  fallbackName: string,
): DocTypeMeta {
  const root =
    isRecord(payload) && 'message' in payload ? payload['message'] : payload

  let meta: unknown = root
  if (
    isRecord(root) &&
    Array.isArray(root['docs']) &&
    root['docs'].length > 0
  ) {
    meta = root['docs'][0]
  }
  if (!isRecord(meta)) {
    throw new Error(
      `[newui/vite] unexpected DocType response for "${fallbackName}"`,
    )
  }

  const fields = Array.isArray(meta['fields'])
    ? meta['fields'].filter(isRecord).map(normalizeField)
    : []

  return {
    name: typeof meta['name'] === 'string' ? meta['name'] : fallbackName,
    istable: meta['istable'] === true,
    fields,
  }
}

/** Fetch one DocType's metadata from the backend. */
export async function fetchDocTypeMeta(
  doctype: string,
  options: GenerateDocTypesOptions,
): Promise<DocTypeMeta> {
  const base = (options.url ?? '').replace(/\/$/, '')
  const endpoint = `${base}/api/method/frappe.client.get_meta?doctype=${encodeURIComponent(doctype)}`
  const fetchImpl = options.fetch ?? globalThis.fetch

  const response = await fetchImpl(endpoint, {
    headers: { Accept: 'application/json', ...options.headers },
  })
  if (!response.ok) {
    throw new Error(
      `[newui/vite] ${doctype}: backend returned ${response.status} ${response.statusText}`,
    )
  }

  return extractDocTypeMeta(await response.json(), doctype)
}

/**
 * Fetch every configured DocType and write the interfaces to `output`. The file
 * is only rewritten when its content changes, so it is safe to call on every
 * dev-server start.
 */
export async function generateDocTypes(
  options: GenerateDocTypesOptions,
): Promise<GenerateDocTypesResult> {
  const output = options.output ?? 'src/types/doctypes.ts'
  const outputPath = path.isAbsolute(output)
    ? output
    : path.resolve(process.cwd(), output)

  const metas = await Promise.all(
    options.doctypes.map((doctype) => fetchDocTypeMeta(doctype, options)),
  )
  const source = generateDocTypeSource(metas)
  const doctypes = metas.map((meta) => meta.name)

  await mkdir(path.dirname(outputPath), { recursive: true })
  const previous = await readFile(outputPath, 'utf8').catch(() => null)
  if (previous === source)
    return { output: outputPath, written: false, doctypes }

  await writeFile(outputPath, source)
  return { output: outputPath, written: true, doctypes }
}

/**
 * The `doctypeTypes` Vite plugin: regenerates interfaces when the dev server
 * starts. Failures warn rather than abort — a backend that is down should not
 * stop the frontend from booting.
 */
export function doctypeTypes(options: GenerateDocTypesOptions): Plugin {
  return {
    name: 'newui:doctype-types',
    apply: 'serve',
    async buildStart() {
      try {
        await generateDocTypes(options)
      } catch (error) {
        const message = error instanceof Error ? error.message : String(error)
        this.warn(`[newui/vite] DocType type generation failed: ${message}`)
      }
    },
  }
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null
}

function normalizeField(value: Record<string, unknown>): DocTypeField {
  const field: DocTypeField = {
    fieldname: typeof value['fieldname'] === 'string' ? value['fieldname'] : '',
    fieldtype:
      typeof value['fieldtype'] === 'string' ? value['fieldtype'] : 'Data',
  }
  if (typeof value['label'] === 'string') field.label = value['label']
  if (typeof value['options'] === 'string') field.options = value['options']
  if (value['reqd'] === true || value['reqd'] === 1) field.reqd = true
  return field
}
